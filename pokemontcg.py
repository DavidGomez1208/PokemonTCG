"""
## Paso 1: Preparación del Dataset y Variable Objetivo
Seleccionamos y limpiamos las columnas, removiendo aquellas que pueden ocasionar fuga de datos, y aplicamos la transformación logarítmica a la variable dependiente.
"""

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split

# Filtrar nulos en el target
df_model_clean = df_completo.dropna(subset=['price_usd']).copy()

# Evitar fugas de datos eliminando variables directamente correlacionadas al precio
features_to_drop = ['price', 'price_usd', 'price_tier_usd', 'currency', 'Name', 'name_clean', '#']
features_list = [col for col in df_model_clean.columns if col not in features_to_drop]

X_final = df_model_clean[features_list]
y_final_log = np.log1p(df_model_clean['price_usd'])

"""
## Paso 2: División en Entrenamiento y Prueba
Dividimos los datos de manera aleatoria pero reproducible.
"""

X_train_f, X_test_f, y_train_f, y_test_f = train_test_split(
    X_final, y_final_log, test_size=0.2, random_state=42
)

print(f"Registros de entrenamiento: {len(X_train_f)}")
print(f"Registros de prueba: {len(X_test_f)}")

"""
## Paso 3: Configuración del Pipeline de Preprocesamiento
Creamos los transformadores específicos para las variables numéricas y categóricas detectadas automáticamente.
"""

from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler, OneHotEncoder

# Separar tipo de columnas automáticamente
numeric_cols = X_final.select_dtypes(include=['int64', 'float64']).columns.tolist()
categorical_cols = X_final.select_dtypes(include=['object', 'bool']).columns.tolist()

# Pipelines de preprocesamiento
numeric_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='median')),
    ('scaler', StandardScaler())
])

categorical_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='constant', fill_value='missing')),
    ('onehot', OneHotEncoder(handle_unknown='ignore'))
])

preprocessor = ColumnTransformer(transformers=[
    ('num', numeric_transformer, numeric_cols),
    ('cat', categorical_transformer, categorical_cols)
])

"""
## Paso 4: Definición del Modelo y Entrenamiento
Acoplamos el preprocesamiento con el regresor RandomForest dentro de un único Pipeline y ajustamos el modelo.
"""

from sklearn.ensemble import RandomForestRegressor

# Enlazar preprocesamiento y algoritmo
final_model_pipeline = Pipeline(steps=[
    ('preprocessor', preprocessor),
    ('regressor', RandomForestRegressor(n_estimators=150, max_depth=10, random_state=42))
])

# Ajustar el pipeline

final_model_pipeline.fit(X_train_f, y_train_f)

"""
## Paso 5: Evaluación de Métricas
Generamos las predicciones y calculamos el rendimiento en escala logarítmica y original (dólares).
"""

from sklearn.metrics import r2_score, mean_absolute_error

# Predicción y transformación inversa
y_pred_log = final_model_pipeline.predict(X_test_f)
y_pred_usd = np.expm1(y_pred_log)
y_test_usd = np.expm1(y_test_f)

# Métricas finales
r2_log = r2_score(y_test_f, y_pred_log)
r2_usd = r2_score(y_test_usd, y_pred_usd)
mae_usd = mean_absolute_error(y_test_usd, y_pred_usd)

print(f"R² Score (Escala Logarítmica): {r2_log:.4f}")
print(f"R² Score (Escala Original USD): {r2_usd:.4f}")
print(f"Error Absoluto Medio (MAE): ${mae_usd:.2f} USD")

import matplotlib.pyplot as plt
